const LANGUAGES: Record<string, Strings> = { en, ru, de, zh, ja };

export type StringKey = keyof Strings;
export type Translator = (key: StringKey, variables?: Record<string, string>) => string;

export function pickLanguage(locale: string): keyof typeof LANGUAGES {
  const base = locale.toLowerCase().split(/[-_]/)[0] ?? "en";
  return base in LANGUAGES ? base : "en";
}

export function createTranslator(locale: string): { language: string; strings: Strings; t: Translator } {
  const language = pickLanguage(locale);
  const strings = LANGUAGES[language]!;
  const t: Translator = (key, variables = {}) => strings[key].replace(/\{(\w+)\}/g, (_, name: string) => variables[name] ?? "");
  return { language, strings, t };
}

export const ALL_LANGUAGES = LANGUAGES;
