export type PartyTranslate = (key: PartyTextKey, variables?: Record<string, string | number>) => string;

export function partyText(language: string): PartyTranslate {
  const table: Record<string, string> = language === "ru" ? RU : EN;
  return (key, variables) => {
    let text = table[key] ?? key;
    for (const [name, value] of Object.entries(variables ?? {})) text = text.split(`{{${name}}}`).join(String(value));
    return text;
  };
}

export function partyError(t: PartyTranslate, code: string): string {
  const key = `error_${code}` as PartyTextKey;
  return key in RU ? t(key) : t("error_generic", { code });
}

export function roleName(t: PartyTranslate, role: MafiaRole): string {
  return t(`role_${role}` as PartyTextKey);
}

export function logLine(t: PartyTranslate, entry: MafiaLogEntry): string {
  const role = (value: MafiaRole | null) => value ? ` — ${roleName(t, value).toLowerCase()}` : "";
  switch (entry.kind) {
    case "start": return t("log_start", { players: entry.players, mafia: entry.mafia });
    case "night": return t("log_night", { round: entry.round });
    case "killed": return t("log_killed", { name: entry.name, role: role(entry.role) });
    case "quiet": return t("log_quiet");
    case "executed": return t("log_executed", { name: entry.name, role: role(entry.role), votes: entry.votes });
    case "spared": return t("log_spared");
    case "left": return t("log_left", { name: entry.name, role: role(entry.role) });
    case "win": return t(entry.side === "town" ? "log_win_town" : "log_win_mafia");
  }
}
