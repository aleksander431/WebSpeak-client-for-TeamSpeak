export function editorText(russian: boolean): EditorText {
  return russian ? ru : en;
}

/** A draft problem in the page's language. */
export function explainProblem(t: EditorText, message: string): string {
  const reason = message.includes(": ") ? message.slice(message.lastIndexOf(": ") + 2) : message;
  return t.problems[reason] ?? reason;
}

export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}
